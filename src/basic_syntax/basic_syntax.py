# ============================================================
# PySpark Basic Syntax
# ============================================================


# ------------------------------------------------------------
# 1. Import SparkSession
# ------------------------------------------------------------

from pyspark.sql import SparkSession


# ------------------------------------------------------------
# 2. Create Spark Session
# ------------------------------------------------------------

spark = SparkSession.builder \
    .appName("PySpark Basics") \
    .getOrCreate()


# ------------------------------------------------------------
# 3. Create a DataFrame
# ------------------------------------------------------------

data = [
    (1, "Rahul", 25000),
    (2, "Amit", 30000),
    (3, "Neha", 35000)
]

df = spark.createDataFrame(
    data,
    ["id", "name", "salary"]
)


# ------------------------------------------------------------
# 4. Display DataFrame
# ------------------------------------------------------------

df.show()


# ------------------------------------------------------------
# 5. Display Schema
# ------------------------------------------------------------

df.printSchema()


# ------------------------------------------------------------
# 6. Select Columns
# ------------------------------------------------------------

df2 = df.select(
    "id",
    "name",
    "salary"
)


# ------------------------------------------------------------
# 7. Filter Rows
# ------------------------------------------------------------

from pyspark.sql.functions import col

df3 = df.filter(
    col("salary") > 30000
)


# ------------------------------------------------------------
# 8. Add a New Column
# ------------------------------------------------------------

df4 = df.withColumn(
    "annual_salary",
    col("salary") * 12
)


# ------------------------------------------------------------
# 9. Rename a Column
# ------------------------------------------------------------

df5 = df.withColumnRenamed(
    "salary",
    "monthly_salary"
)


# ------------------------------------------------------------
# 10. Drop a Column
# ------------------------------------------------------------

df6 = df.drop("salary")


# ------------------------------------------------------------
# 11. Sort Data
# ------------------------------------------------------------

df7 = df.sort(
    col("salary").desc()
)


# ------------------------------------------------------------
# 12. Remove Duplicate Rows
# ------------------------------------------------------------

df8 = df.dropDuplicates()


# ------------------------------------------------------------
# 13. Limit Rows
# ------------------------------------------------------------

df9 = df.limit(2)


# ------------------------------------------------------------
# 14. Count Rows
# ------------------------------------------------------------

df.count()


# ------------------------------------------------------------
# 15. Conditional Column
# ------------------------------------------------------------

from pyspark.sql.functions import when

df10 = df.withColumn(
    "category",
    when(col("salary") >= 30000, "High")
    .otherwise("Low")
)


# ------------------------------------------------------------
# 16. Group By
# ------------------------------------------------------------

df11 = df.groupBy(
    "salary"
).count()


# ------------------------------------------------------------
# 17. Aggregation
# ------------------------------------------------------------

from pyspark.sql.functions import (
    sum,
    avg,
    min,
    max,
    count
)

df12 = df.agg(
    sum("salary").alias("total_salary"),
    avg("salary").alias("average_salary"),
    min("salary").alias("minimum_salary"),
    max("salary").alias("maximum_salary"),
    count("id").alias("employee_count")
)


# ------------------------------------------------------------
# 18. Read CSV
# ------------------------------------------------------------

df13 = spark.read.csv(
    "data.csv",
    header=True,
    inferSchema=True
)


# ------------------------------------------------------------
# 19. Read JSON
# ------------------------------------------------------------

df14 = spark.read.json(
    "data.json"
)


# ------------------------------------------------------------
# 20. Read Parquet
# ------------------------------------------------------------

df15 = spark.read.parquet(
    "data.parquet"
)


# ------------------------------------------------------------
# 21. Write CSV
# ------------------------------------------------------------

df.write \
    .mode("overwrite") \
    .option("header", True) \
    .csv("output/csv")


# ------------------------------------------------------------
# 22. Write JSON
# ------------------------------------------------------------

df.write \
    .mode("overwrite") \
    .json("output/json")


# ------------------------------------------------------------
# 23. Write Parquet
# ------------------------------------------------------------

df.write \
    .mode("overwrite") \
    .parquet("output/parquet")


# ------------------------------------------------------------
# 24. Join DataFrames
# ------------------------------------------------------------

df2 = df1.alias("a").join(
    df2.alias("b"),
    df1.id == df2.id,
    "inner"
)


# ------------------------------------------------------------
# 25. Union DataFrames
# ------------------------------------------------------------

df3 = df1.union(df2)


# ------------------------------------------------------------
# 26. Union By Column Name
# ------------------------------------------------------------

df4 = df1.unionByName(df2)


# ------------------------------------------------------------
# 27. Handle Null Values
# ------------------------------------------------------------

df5 = df.fillna(0)


# ------------------------------------------------------------
# 28. Drop Null Values
# ------------------------------------------------------------

df6 = df.dropna()


# ------------------------------------------------------------
# 29. String Functions
# ------------------------------------------------------------

from pyspark.sql.functions import upper, lower, trim, length

df16 = df.withColumn(
    "upper_name",
    upper("name")
)

df17 = df.withColumn(
    "lower_name",
    lower("name")
)

df18 = df.withColumn(
    "trimmed_name",
    trim("name")
)

df19 = df.withColumn(
    "name_length",
    length("name")
)


# ------------------------------------------------------------
# 30. Date Functions
# ------------------------------------------------------------

from pyspark.sql.functions import current_date, current_timestamp

df20 = df.withColumn(
    "current_date",
    current_date()
)

df21 = df.withColumn(
    "current_timestamp",
    current_timestamp()
)


# ------------------------------------------------------------
# 31. Cast Data Type
# ------------------------------------------------------------

from pyspark.sql.types import IntegerType

df22 = df.withColumn(
    "salary",
    col("salary").cast(IntegerType())
)


# ------------------------------------------------------------
# 32. Array Functions
# ------------------------------------------------------------

from pyspark.sql.functions import array, array_contains, array_size

df23 = df.withColumn(
    "skills",
    array("skill1", "skill2")
)

df24 = df.withColumn(
    "has_python",
    array_contains("skills", "Python")
)

df25 = df.withColumn(
    "skill_count",
    array_size("skills")
)


# ------------------------------------------------------------
# 33. Explode Array
# ------------------------------------------------------------

from pyspark.sql.functions import explode

df26 = df.select(
    "id",
    explode("skills").alias("skill")
)


# ------------------------------------------------------------
# 34. Window Function
# ------------------------------------------------------------

from pyspark.sql.window import Window
from pyspark.sql.functions import row_number

window = Window.orderBy(
    col("salary").desc()
)

df27 = df.withColumn(
    "row_number",
    row_number().over(window)
)


# ------------------------------------------------------------
# 35. Cache DataFrame
# ------------------------------------------------------------

df.cache()


# ------------------------------------------------------------
# 36. Check Cache Status
# ------------------------------------------------------------

df.is_cached


# ------------------------------------------------------------
# 37. Remove DataFrame from Cache
# ------------------------------------------------------------

df.unpersist()


# ------------------------------------------------------------
# 38. Stop Spark Session
# ------------------------------------------------------------

spark.stop()